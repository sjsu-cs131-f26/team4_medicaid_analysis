CREATE TABLE hcpcs_sum AS 
SELECT 
	HCPCS_CODE, 
	CLAIM_FROM_MONTH, 
	SUM(TOTAL_CLAIM_LINES) AS TOTAL_CLAIM_LINES_SUM, 
	SUM(TOTAL_PAID) AS TOTAL_PAID_SUM 
FROM read_csv_auto('../work/analysis_ready.tsv', delim = '\t') 
GROUP BY
	HCPCS_CODE, 
	CLAIM_FROM_MONTH 
ORDER BY 
	HCPCS_CODE ASC, 
	CLAIM_FROM_MONTH ASC; 

CREATE TABLE duckdb_result AS
SELECT
    HCPCS_CODE,
    (SELECT CLAIM_FROM_MONTH FROM hcpcs_sum h2
     WHERE h2.HCPCS_CODE = h1.HCPCS_CODE
     ORDER BY TOTAL_PAID_SUM / TOTAL_CLAIM_LINES_SUM ASC,
              CLAIM_FROM_MONTH ASC LIMIT 1) AS LOWEST_PAID_MONTH,
    (SELECT CLAIM_FROM_MONTH FROM hcpcs_sum h2
     WHERE h2.HCPCS_CODE = h1.HCPCS_CODE
     ORDER BY TOTAL_PAID_SUM / TOTAL_CLAIM_LINES_SUM DESC,
              CLAIM_FROM_MONTH ASC LIMIT 1) AS HIGHEST_PAID_MONTH,
    ARG_MIN(CLAIM_FROM_MONTH, TOTAL_CLAIM_LINES_SUM) AS LOWEST_DEMAND_MONTH,
    ARG_MAX(CLAIM_FROM_MONTH, TOTAL_CLAIM_LINES_SUM) AS HIGHEST_DEMAND_MONTH
FROM hcpcs_sum h1
GROUP BY HCPCS_CODE
ORDER BY HCPCS_CODE ASC;

COPY duckdb_result TO '../out/duckdb_text_result.tsv' (HEADER, DELIMITER '\t');
